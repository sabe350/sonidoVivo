CREATE TABLE IF NOT EXISTS PRODUCT (
       ID VARCHAR2(5) PRIMARY KEY,
       STOCK INT NOT NULL,
       NOMBRE VARCHAR2 NOT NULL,
        MARCA VARCHAR2 NOT NULL,
    MODELO VARCHAR2 NOT NULL,
    PRECIO INT NOT NULL
);

CREATE TABLE IF NOT EXISTS USUARIO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    PASSWORD VARCHAR2 NOT NULL,
    NOMBRE VARCHAR2,
    APELLIDO VARCHAR2,
    CORREO VARCHAR2 NOT NULL,
    TELEFONO INT,
    REGION VARCHAR2,
    CIUDAD VARCHAR2,
    DIRECCION VARCHAR2,
    ROLE VARCHAR2 NOT NULL
);

CREATE TABLE IF NOT EXISTS ORDEN (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BUY_ORDER  VARCHAR(26)  NOT NULL UNIQUE,
    TOKEN VARCHAR(100) NOT NULL UNIQUE,
    TOTAL BIGINT NOT NULL,
    ESTADO VARCHAR(20)  NOT NULL
);

CREATE TABLE IF NOT EXISTS ORDEN_ITEM (
  ORDEN_ID BIGINT NOT NULL,
  PRODUCT_ID VARCHAR(5) NOT NULL,
  CANTIDAD INT NOT NULL,
  CONSTRAINT FK_ORDEN_ITEM_ORDEN
  FOREIGN KEY (ORDEN_ID) REFERENCES ORDEN(ID) ON DELETE CASCADE
);